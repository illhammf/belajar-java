package pertemuan_03.contoh;

public class IfSatu1 {

    public static void main(String[] args) {

        // Deklarasi variabel
        int a = 1, b = 10;

        // Memeriksa apakah a kurang dari 5
        if (a < 5) {
            System.out.println("Nilai a lebih kecil dari 5");
        }

        // Memeriksa apakah b kurang dari 5
        if (b < 5) {
            System.out.println("Nilai b lebih kecil dari 5");
        }
    }
}
